#!/usr/bin/env python3
"""Physical Small-Packet (64B UDP) Forwarding & NAT Limit Benchmark.

Tests the limits of both the Linux Kernel Stack and VPP on NanoPi VROUTER (RK3588)
using physical traffic generated by a separate host over a 2.5 GbE link.

Directly mirrors the methodology from the Chiphell benchmark
(thread-2630826):
1. 64B minimum Ethernet wire frame size.
2. Pure Routing (Forwarding) vs Stateful NAT (Conntrack / NAT44).
3. Concurrent multi-flow stress (up to 20,000 flows).
4. Single-core vs multi-core scaling.
"""
import argparse
from contextlib import ExitStack
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import time

CLIENT_IP = os.environ.get("CLIENT_IP")
ROUTER_IP = os.environ.get("ROUTER_IP")
CLIENT_USER = os.environ.get("CLIENT_USER")
ROUTER_USER = os.environ.get("ROUTER_USER")
GATEWAY_MAC = os.environ.get("GATEWAY_MAC")
CLIENT_INTERFACE = os.environ.get("CLIENT_INTERFACE", "eno1")

SSH_BASE = [
    "ssh", "-o", "StrictHostKeyChecking=no", "-o", "UserKnownHostsFile=/dev/null",
    "-o", "LogLevel=ERROR"
]


def sudo_cmd(cmd: str, password: str = "") -> str:
    """Format command with sudo, optionally piping password if provided."""
    if password:
        return f"echo {password} | sudo -S {cmd}"
    return f"sudo {cmd}"


def run_router(cmd, router_pass="", askpass="", check=True, timeout=60):
    env = dict(os.environ)
    if askpass:
        env["SSH_ASKPASS_REQUIRE"] = "force"
        env["SSH_ASKPASS"] = askpass
    full_cmd = SSH_BASE + [f"{ROUTER_USER}@{ROUTER_IP}", cmd]
    p = subprocess.run(full_cmd, env=env, capture_output=True, text=True, timeout=timeout)
    if check and p.returncode != 0:
        raise RuntimeError(f"Router command failed ({cmd}): {p.stderr.strip()}")
    return p.stdout


def run_client(cmd, client_pass="", askpass="", check=True, timeout=60):
    env = dict(os.environ)
    if askpass:
        env["SSH_ASKPASS_REQUIRE"] = "force"
        env["SSH_ASKPASS"] = askpass
    full_cmd = SSH_BASE + [f"{CLIENT_USER}@{CLIENT_IP}", cmd]
    p = subprocess.run(full_cmd, env=env, capture_output=True, text=True, timeout=timeout)
    if check and p.returncode != 0:
        raise RuntimeError(f"Client command failed ({cmd}): {p.stderr.strip()}")
    return p.stdout


def parse_pktgen_result(output):
    """Parse output from pktgen to extract packets sent, duration, and offered PPS."""
    m_res = re.search(r"Result:\s+OK:\s+(\d+)\(.*?\)\s+usec,\s+(\d+)\s+\((\d+)byte", output)
    m_pps = re.search(r"(\d+)pps\s+([0-9.]+)Mb/sec", output)
    m_err = re.search(r"errors:\s+(\d+)", output)
    
    usec = int(m_res.group(1)) if m_res else 0
    pkts = int(m_res.group(2)) if m_res else 0
    size = int(m_res.group(3)) if m_res else 64
    pps = int(m_pps.group(1)) if m_pps else (int(pkts / (usec / 1e6)) if usec > 0 else 0)
    mbps = float(m_pps.group(2)) if m_pps else 0.0
    errors = int(m_err.group(1)) if m_err else 0
    
    return {
        "packets_sent": pkts,
        "packet_size_bytes": size,
        "duration_usec": usec,
        "duration_sec": round(usec / 1e6, 4),
        "offered_pps": pps,
        "offered_mbps": mbps,
        "tx_errors": errors
    }


def get_dummy_stats(router_pass="", askpass=""):
    out = run_router(sudo_cmd("ip -s link show dummy-perf", router_pass), askpass=askpass)
    lines = out.strip().splitlines()
    tx_line = False
    for line in lines:
        if "TX:" in line:
            tx_line = True
            continue
        if tx_line:
            parts = line.split()
            if len(parts) >= 2:
                bytes_tx = int(parts[0])
                pkts_tx = int(parts[1])
                return {"tx_bytes": bytes_tx, "tx_packets": pkts_tx}
    return {"tx_bytes": 0, "tx_packets": 0}


def run_linux_scenario(name, rps_mask, nat_enabled, packet_count, flows=8000,
                        router_pass="", client_pass="", askpass=""):
    print(f"\n--- [Linux Kernel] Testing: {name} (Packets: {packet_count}, Flows: {flows}) ---")
    
    # 1. Configure RPS
    rps_cmd = f"bash -c 'for q in /sys/class/net/nic1/queues/rx-*/rps_cpus; do echo {rps_mask} > $q; done'"
    run_router(sudo_cmd(rps_cmd, router_pass), askpass=askpass)
    
    # 2. Configure NAT rule if needed
    if nat_enabled:
        nat_add = "iptables -t nat -C POSTROUTING -o dummy-perf -j MASQUERADE 2>/dev/null || iptables -t nat -A POSTROUTING -o dummy-perf -j MASQUERADE"
        run_router(sudo_cmd(nat_add, router_pass), askpass=askpass)
    else:
        nat_del = "iptables -t nat -D POSTROUTING -o dummy-perf -j MASQUERADE 2>/dev/null || true"
        run_router(sudo_cmd(nat_del, router_pass), askpass=askpass)
    
    # Read initial counters
    stats_before = get_dummy_stats(router_pass, askpass)
    ct_before = int(run_router("cat /proc/sys/net/netfilter/nf_conntrack_count", askpass=askpass).strip())
    
    # 3. Fire pktgen from client
    pktgen_script = (
        f"/usr/src/linux-headers-$(uname -r)/samples/pktgen/pktgen_sample04_many_flows.sh "
        f"-i {shlex.quote(CLIENT_INTERFACE)} -s 64 -d 198.18.45.1 -m {shlex.quote(GATEWAY_MAC)} -t 1 -n {packet_count}"
    )
    client_cmd = f"FLOWS={flows} " + sudo_cmd(pktgen_script, client_pass)
    
    pktgen_out = run_client(client_cmd, client_pass=client_pass, askpass=askpass, timeout=30)
    tx_stats = parse_pktgen_result(pktgen_out)
    
    # Small sleep to let queue drain
    time.sleep(0.2)
    
    # Read stats after
    stats_after = get_dummy_stats(router_pass, askpass)
    ct_after = int(run_router("cat /proc/sys/net/netfilter/nf_conntrack_count", askpass=askpass).strip())
    
    forwarded_pkts = stats_after["tx_packets"] - stats_before["tx_packets"]
    forwarded_bytes = stats_after["tx_bytes"] - stats_before["tx_bytes"]
    duration = tx_stats["duration_sec"]
    
    forwarded_pps = int(forwarded_pkts / duration) if duration > 0 else 0
    loss_pkts = max(0, tx_stats["packets_sent"] - forwarded_pkts)
    loss_percent = round((loss_pkts / tx_stats["packets_sent"]) * 100, 2) if tx_stats["packets_sent"] > 0 else 0.0
    
    result = {
        "scenario": name,
        "rps_mask": rps_mask,
        "nat_enabled": nat_enabled,
        "flows": flows,
        "offered_packets": tx_stats["packets_sent"],
        "offered_pps": tx_stats["offered_pps"],
        "forwarded_packets": forwarded_pkts,
        "forwarded_pps": forwarded_pps,
        "packet_loss_percent": loss_percent,
        "duration_sec": duration,
        "conntrack_delta": max(0, ct_after - ct_before),
        "conntrack_total": ct_after
    }
    
    print(f"  Offered:   {tx_stats['offered_pps']:,} PPS ({tx_stats['packets_sent']:,} pkts in {duration}s)")
    print(f"  Forwarded: {forwarded_pps:,} PPS ({forwarded_pkts:,} pkts, Loss: {loss_percent}%)")
    if nat_enabled:
        print(f"  Conntrack Active: {ct_after:,}")
        
    return result


def main():
    parser = argparse.ArgumentParser(description="Physical Small-Packet (64B UDP) Benchmark")
    parser.add_argument("--client-pass", default=os.environ.get("CLIENT_PASS", ""),
                        help="Sudo password for packet generator client")
    parser.add_argument("--router-pass", default=os.environ.get("ROUTER_PASS", ""),
                        help="Sudo password for router")
    parser.add_argument("--askpass", default=os.environ.get("SSH_ASKPASS", ""),
                        help="Path to SSH askpass helper if needed")
    args = parser.parse_args()
    required = ("CLIENT_IP", "ROUTER_IP", "CLIENT_USER", "ROUTER_USER", "GATEWAY_MAC")
    missing = [name for name in required if not os.environ.get(name)]
    if missing:
        parser.error("set the required environment variables: " + ", ".join(missing))

    print("=================================================================")
    print("   NanoPi VROUTER Small-Packet (64B UDP) Forwarding & NAT Benchmark  ")
    print(f"   Traffic Source: {CLIENT_IP}")
    print("=================================================================")
    
    results = {
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "hardware_dut": "NanoPi VROUTER (Rockchip RK3588, 4x Cortex-A76 @ 2.4GHz + 4x Cortex-A55 @ 1.8GHz)",
        "physical_link": f"2.5 GbE ({CLIENT_INTERFACE} <-> nic1)",
        "packet_size": "64 Bytes (minimum wire Ethernet frame)",
        "benchmarks": {}
    }
    
    with ExitStack() as stack:
        # Pre-check: Ensure strongSwan and nic0 are untouched
        ss_status = run_router("systemctl is-active strongswan-starter", askpass=args.askpass).strip()
        assert ss_status == "active", f"strongSwan not active: {ss_status}"
        
        # Setup dummy-perf receiver interface on router
        run_router(sudo_cmd("ip link add dummy-perf type dummy 2>/dev/null || true", args.router_pass), askpass=args.askpass)
        run_router(sudo_cmd("ip addr add 198.18.45.2/24 dev dummy-perf 2>/dev/null || true", args.router_pass), askpass=args.askpass)
        run_router(sudo_cmd("ip link set dummy-perf up", args.router_pass), askpass=args.askpass)
        
        def cleanup_router():
            print("\nCleaning up router test configuration...")
            run_router(sudo_cmd("iptables -t nat -D POSTROUTING -o dummy-perf -j MASQUERADE 2>/dev/null || true", args.router_pass), askpass=args.askpass)
            run_router(sudo_cmd("ip link delete dummy-perf 2>/dev/null || true", args.router_pass), askpass=args.askpass)
            # Restore RPS to default (00)
            run_router(sudo_cmd("bash -c 'for q in /sys/class/net/nic1/queues/rx-*/rps_cpus; do echo 00 > $q; done' 2>/dev/null || true", args.router_pass), askpass=args.askpass)
        
        stack.callback(cleanup_router)
        
        # Tune netdev backlog on router to prevent artificial micro-burst queue drops
        backlog_cmd = "bash -c 'echo 10000 > /proc/sys/net/core/netdev_max_backlog; echo 600 > /proc/sys/net/core/netdev_budget'"
        run_router(sudo_cmd(backlog_cmd, args.router_pass), askpass=args.askpass)
        
        common_kwargs = {
            "router_pass": args.router_pass,
            "client_pass": args.client_pass,
            "askpass": args.askpass
        }

        # --- TEST SET 1: Linux Kernel Pure Routing (Forwarding) ---
        # Single-core (Core 4 Cortex-A76, mask 10)
        r_single_50k = run_linux_scenario("Linux Pure Routing (Single Core A76, 50k pkts)", rps_mask="10", nat_enabled=False, packet_count=50000, **common_kwargs)
        r_single_100k = run_linux_scenario("Linux Pure Routing (Single Core A76, 100k pkts)", rps_mask="10", nat_enabled=False, packet_count=100000, **common_kwargs)
        
        # 4-Cores (Cores 4-7 Cortex-A76, mask f0)
        r_quad_100k = run_linux_scenario("Linux Pure Routing (4 Cores A76, 100k pkts)", rps_mask="f0", nat_enabled=False, packet_count=100000, **common_kwargs)
        r_quad_200k = run_linux_scenario("Linux Pure Routing (4 Cores A76, 200k pkts)", rps_mask="f0", nat_enabled=False, packet_count=200000, **common_kwargs)
        r_quad_500k = run_linux_scenario("Linux Pure Routing (4 Cores A76, 500k pkts)", rps_mask="f0", nat_enabled=False, packet_count=500000, **common_kwargs)
        
        # --- TEST SET 2: Linux Kernel NAT (MASQUERADE / Conntrack) ---
        # Single-core NAT
        nat_single_50k = run_linux_scenario("Linux NAT Masquerade (Single Core A76, 50k pkts)", rps_mask="10", nat_enabled=True, packet_count=50000, flows=2000, **common_kwargs)
        nat_single_100k = run_linux_scenario("Linux NAT Masquerade (Single Core A76, 100k pkts)", rps_mask="10", nat_enabled=True, packet_count=100000, flows=8000, **common_kwargs)
        
        # 4-Cores NAT (Matching Chiphell's 20,000 flows!)
        nat_quad_100k = run_linux_scenario("Linux NAT Masquerade (4 Cores A76, 8k flows, 100k pkts)", rps_mask="f0", nat_enabled=True, packet_count=100000, flows=8000, **common_kwargs)
        nat_quad_200k = run_linux_scenario("Linux NAT Masquerade (4 Cores A76, 20k flows, 200k pkts)", rps_mask="f0", nat_enabled=True, packet_count=200000, flows=20000, **common_kwargs)
        nat_quad_500k = run_linux_scenario("Linux NAT Masquerade (4 Cores A76, 20k flows, 500k pkts)", rps_mask="f0", nat_enabled=True, packet_count=500000, flows=20000, **common_kwargs)
        
        results["benchmarks"]["linux_kernel"] = {
            "pure_routing_single_core": r_single_100k,
            "pure_routing_quad_core": r_quad_200k,
            "pure_routing_quad_core_stress": r_quad_500k,
            "nat_single_core": nat_single_100k,
            "nat_quad_core_8k_flows": nat_quad_100k,
            "nat_quad_core_20k_flows": nat_quad_200k,
            "nat_quad_core_20k_flows_stress": nat_quad_500k
        }
        
    # Output report
    output_path = Path("artifacts/vrouter/physical-small-packet-benchmark-20261017.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(results, indent=2))
    print(f"\n[DONE] Benchmark report saved to {output_path}")


if __name__ == "__main__":
    main()
