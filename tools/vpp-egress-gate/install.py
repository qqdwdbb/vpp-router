def exit_choices(known, clients):
    """What can be picked, in the order listed: an interface clients arrive on cannot also take them out."""
    return sorted(name for name in known if name not in clients)


def parse_exit_names(text, known, clients):
    """The interfaces meant, by number in the list, name or address. An empty list means the
    interfaces could not be read, so a name is all there is, and nothing can be checked."""
    choices = exit_choices(known, clients)
    names = []
    for word in words(text):
        if word.isdigit() and known:
            if not 1 <= int(word) <= len(choices):
                raise ValueError(f'没有序号 {word}，可选 1 到 {len(choices)}')
            name = choices[int(word) - 1]
        else:
            found = [n for n, addresses in known.items()
                     if word == n or any(word in (a, a.split('/')[0]) for a in addresses)]
            if known and not found:
                raise ValueError(f'列表里没有 {word}，请填序号')
            name = found[0] if found else word
        if name in clients:
            raise ValueError(f'{name} 是客户端所在的接口，不能作为出口')
        if name not in names:
            names.append(name)
    return names


def parse_vias(text, use_ipv6):
    """A next hop for each family the exit carries."""
    vias = [parse_address(word) for word in words(text)]
    if not vias:
        raise ValueError('要填下一跳地址')
    if len({via.version for via in vias}) != len(vias):
        raise ValueError('IPv4 和 IPv6 各填一个下一跳')
    if not use_ipv6 and any(via.version == 6 for via in vias):
        raise ValueError('客户端网段没有 IPv6，不能填 IPv6 下一跳')
    return [str(via) for via in vias]


def parse_gateways(text, use_ipv6):
    """Empty for an interface that reaches its peer directly, and the word ipv6 if it carries
    IPv6 that way. Several IPv4 gateways mean several uplinks: a rule each."""
    tokens = words(text)
    direct_ipv6 = 'ipv6' in tokens
    addresses = [parse_address(word) for word in tokens if word != 'ipv6']
    gateways = [str(a) for a in addresses if a.version == 4]
    gateways6 = [str(a) for a in addresses if a.version == 6]
    if len(gateways6) > 1:
        raise ValueError('IPv6 网关最多填一个')
    if direct_ipv6 and addresses:
        raise ValueError('ipv6 这个词只用于没有网关的隧道，不能和地址一起填')
    if (direct_ipv6 or gateways6) and not use_ipv6:
        raise ValueError('客户端网段没有 IPv6，这里不能带 IPv6')
    if gateways6 and len(gateways) > 1:
        raise ValueError('多个 IPv4 网关会生成多条规则，不能同时带 IPv6；安装后可在规则里手动加 ipv6 和 gateway6')
    return {'gateways': gateways, 'gateway6': gateways6[0] if gateways6 else None, 'ipv6': direct_ipv6 or bool(gateways6)}


def parse_vpp_interfaces(address_output):
    """The addresses of each VPP interface that has one."""
    found, current = {}, None
    for line in address_output.splitlines():
        if line and not line[0].isspace():
            current = line.split()[0]
            continue
        match = re.match(r'\s*L3 ([0-9a-fA-F.:]+/\d+)', line)
        if match:
            found.setdefault(current, []).append(match.group(1))
    return found


def linux_interfaces(links):
    """The addresses of each Linux interface that could carry traffic."""
    found = {}
    for link in links:
        name = link.get('ifname', '')
        addresses = [a['local'] for a in link.get('addr_info', []) if a.get('scope') == 'global' and a.get('local')]
        if addresses and 'UP' in link.get('flags', []) and link.get('link_type') != 'loopback' and not OWN_DEVICE.match(name):
            found[name] = addresses
    return found


def listing(interfaces, clients):
    """Numbered as parse_exit_names reads them, with what cannot be picked set apart."""
    if not interfaces:
        return '  （读不到接口，请直接填接口名）'
    lines = [f'  {number}. {name}  {" ".join(interfaces[name])}'
             for number, name in enumerate(exit_choices(interfaces, clients), 1)]
    lines += [f'  -  {name}  {" ".join(interfaces[name])}  （客户端所在的接口，不能作为出口）' for name in sorted(clients) if name in interfaces]
    return '\n'.join(lines)


