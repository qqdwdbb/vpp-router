def lan_interfaces(links, lans):
    """The Linux interfaces on a client network, and every global address they have. A
    redirect sends a query to an address of the interface it came in on, and which one
    is up to the kernel, so Gate must listen on all of them."""
    networks = [ipaddress.ip_network(n) for n in lans]
    names, addresses = [], []
    for link in links:
        name = link.get('ifname', '')
        if link.get('link_type') == 'loopback' or OWN_DEVICE.match(name) or 'UP' not in link.get('flags', []):
            continue
        found = [a['local'] for a in link.get('addr_info', []) if a.get('scope') == 'global' and a.get('local')]
        if any(ipaddress.ip_address(a).version == n.version and ipaddress.ip_address(a) in n for a in found for n in networks):
            names.append(name)
            addresses += found
    return names, addresses


def vpp_hijack_entries(lan_interfaces_of_vpp, addresses):
    """Which VPP interfaces can send their clients' DNS to an address of Linux on that network."""
    entries = []
    for interface, lans in sorted(lan_interfaces_of_vpp.items()):
        via, sources = {}, []
        for lan in lans:
            network = ipaddress.ip_network(lan)
            found = [a for a in addresses if ipaddress.ip_address(a).version == network.version and ipaddress.ip_address(a) in network]
            if found:
                via.setdefault(network.version, found[0])
                sources.append(lan)
        if via:
            entries.append({'interface': interface, 'via': list(via.values()), 'sources': sources})
    return entries


def vpp_interfaces_on(lans, address_output):
    """The VPP interfaces with an address on these networks, whatever NAT does on them:
    NAT as an output feature on the WAN has no inside interface to name."""
    networks = [ipaddress.ip_network(n) for n in lans]
    found, current = {}, None
    for line in address_output.splitlines():
        if line and not line[0].isspace():
            current = line.split()[0]
            continue
        match = re.match(r'\s*L3 ([0-9a-fA-F.:]+/\d+)', line)
        if match:
            network = ipaddress.ip_interface(match.group(1)).network
            if network in networks:
                found.setdefault(current, []).append(str(network))
    return found


def nat_on_ip4_input(features):
    """NAT on an inside interface rewrites the source before ABF can match the client."""
    section = re.search(r'^ip4-unicast:\n((?:[ \t]+\S.*\n?)*)', features, re.M)
    return bool(section and 'in2out' in section.group(1))


def parse_startup(text):
    """What a VPP startup file says about its CLI file and sockets."""
    found = {}
    # A stanza may share one line with its braces, and comments must not count.
    text = re.sub(r'(?m)#.*$', '', text)
    for key, pattern in (('cli_file', r'(?:^|[\s{])(?:exec|startup-config)\s+([^\s}]+)'),
                         ('vpp_socket', r'(?:^|[\s{])cli-listen\s+([^\s}]+)'),
                         ('api_socket', r'(?:^|[\s{])socket-name\s+([^\s}]+)')):
        match = re.search(pattern, text)
        if match:
            found[key] = match.group(1)
    return found


def first_nameserver(text):
    for line in text.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] == 'nameserver':
            return words[1]
    return None


def vpp_startup_file(service):
    show = run('systemctl', 'show', service, '-p', 'ExecStart', '--value')
    match = re.search(r'argv\[\]=\S*/?vpp\s+(?:\S+\s+)*?-c\s+(\S+)', show)
    return Path(match.group(1)) if match else None


def detect_vpp_service():
    listed = run('systemctl', 'list-units', '--type=service', '--state=active', '--no-legend', '--plain')
    found = []
    for line in listed.splitlines():
        words = line.split()
        if words and 'vpp' in words[0] and vpp_startup_file(words[0]):
            found.append(words[0])
    if len(found) != 1:
        raise ValueError(f'cannot tell which service runs VPP ({found or "none found"}); use --vpp-service')
    return found[0]


def say(text):
    """An explanation before a question, which only someone at a terminal needs."""
    if sys.stdin.isatty():
        print(text, file=sys.stderr)


def read_answer(prompt):
    """A line from the person at the terminal, or None when nobody is there to ask."""
    if not sys.stdin.isatty():
        return None
    # On stderr, as a dry run prints its result on stdout.
    print(prompt, end='', file=sys.stderr, flush=True)
    try:
        return input().strip()
    except EOFError as error:
        raise ValueError('输入提前结束，配置没有填完') from error


def ask(prompt, parse, flag=None):
    """Asks until the answer is usable. With nobody to ask, what needs an answer names its flag."""
    while True:
        answer = read_answer(prompt)
        if answer is None:
            if flag:
                raise ValueError(f'没有终端可以询问，请用 {flag} 指定')
            return parse('')
        try:
            return parse(answer)
        except ValueError as error:
            print(f'  {error}', file=sys.stderr)


def words(text):
    return [word for word in re.split(r'[,，\s]+', text) if word]


def parse_address(word):
    try:
        return ipaddress.ip_address(word)
    except ValueError:
        raise ValueError(f'{word} 不是 IP 地址，应写成 10.61.20.1 这样') from None


def parse_lan(word):
    try:
        return str(ipaddress.ip_network(word))
    except ValueError:
        raise ValueError(f'{word} 不是网段，应写成 10.61.30.0/24 这样，最后一段是网段本身，不是接口地址') from None


def parse_lans(text):
    lans = [parse_lan(word) for word in words(text)]
    if not lans:
        raise ValueError('至少要填一个网段')
    return lans


def parse_upstream(text, default=None):
    if not text and not default:
        raise ValueError('要填一个 DNS 服务器地址')
    return str(parse_address(text or default))


def parse_yes(text):
    """Yes unless said otherwise: an empty answer takes the default."""
    word = text.strip().lower()
    if word in ('', 'y', 'yes', '是'):
        return True
    if word in ('n', 'no', '否'):
        return False
    raise ValueError('请填 y 或 n，直接回车表示 y')


