def parse_endpoint(word):
    """An address and port, as 127.0.0.1:7893 or [::1]:7893, or a port alone. A wildcard
    address, or none, comes back as None: the proxy listens on every address."""
    match = re.fullmatch(r'\[([^\]]+)\]:(\d+)|([^:\[\]]+):(\d+)|(\d+)', word)
    if not match:
        raise ValueError(f'{word} 应写成 127.0.0.1:7893、[::1]:7893 这样，或者只写端口')
    text = match.group(1) or match.group(3)
    port = int(match.group(2) or match.group(4) or match.group(5))
    if not 1 <= port <= 65535:
        raise ValueError(f'端口 {port} 不在 1 到 65535 之间')
    address = parse_address(text) if text else None
    if match.group(3) and address and address.version == 6:
        raise ValueError(f'IPv6 地址要加方括号，比如 [{address}]:{port}')
    return (None if address is None or address.is_unspecified else address), port


def parse_tproxy(text, use_ipv6):
    """Where the proxy takes TPROXY traffic: one port, and an address per pool unless it
    listens on every address."""
    endpoints = [parse_endpoint(word) for word in words(text)] or [(None, DEFAULT_TPROXY_PORT)]
    ports = {port for _, port in endpoints}
    if len(ports) != 1:
        raise ValueError('各地址要用同一个端口')
    addresses = [address for address, _ in endpoints if address]
    if len({a.version for a in addresses}) != len(addresses):
        raise ValueError('IPv4 和 IPv6 地址各填一个')
    if not use_ipv6 and any(a.version == 6 for a in addresses):
        raise ValueError('客户端网段没有 IPv6，不能填 IPv6 地址')
    if addresses and use_ipv6 and len(addresses) != 2:
        port = ports.pop()
        raise ValueError(f'客户端网段有 IPv6，IPv4 和 IPv6 地址各填一个，比如 127.0.0.1:{port}, [::1]:{port}；'
                         '客户端监听所有地址时只填端口')
    return {'addresses': [str(a) for a in addresses], 'port': ports.pop()}


def listen_port(text):
    """Gate's own DNS port. 53 is where clients send queries, which reach Gate by redirection."""
    try:
        port = int(text)
    except ValueError:
        raise argparse.ArgumentTypeError(f'{text} is not a port') from None
    if not 1 <= port <= 65535 or port == 53:
        raise argparse.ArgumentTypeError('the port must be 1 to 65535 and not 53')
    return port


def parse_fake_dns(text, listen):
    address, port = parse_endpoint(text) if text else (parse_address(DEFAULT_FAKE_DNS[0]), DEFAULT_FAKE_DNS[1])
    if address is None:
        raise ValueError('Fake-IP DNS 要填具体地址，比如 127.0.0.1:5354')
    if any(str(address) == host and port == listen_port for host, listen_port in listen):
        raise ValueError(f'{address}:{port} 是 Gate 自己监听的地址，要填代理客户端的 Fake-IP DNS')
    return [str(address), port]


